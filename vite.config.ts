import { defineConfig } from "@lovable.dev/vite-tanstack-config";

// Allow external hosts (e.g. Render) to override the Nitro preset via env var.
// Lovable Cloud still uses the default cloudflare-module preset when this is unset.
const renderPreset = process.env["NITRO_PRESET"] || process.env["SERVER_PRESET"];

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  ...(renderPreset ? { nitro: { preset: renderPreset } } : {}),
});
